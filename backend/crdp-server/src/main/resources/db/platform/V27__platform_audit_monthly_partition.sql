-- 归档登记（只追加；UPDATE / DELETE 触发器拦截，逃生口与审计表同口径）
CREATE TABLE aud_archive (
  id BIGINT NOT NULL AUTO_INCREMENT,
  table_name VARCHAR(64) NOT NULL COMMENT '审计表名',
  partition_name VARCHAR(16) NOT NULL COMMENT '月分区名（pYYYYMM）',
  month_first_day DATE NOT NULL COMMENT '分区覆盖月份首日',
  object_key VARCHAR(255) NULL COMMENT 'WORM 桶数据对象键（{前缀}/{表}/{yyyy-MM}.jsonl.gz；空分区为 NULL）',
  row_count BIGINT NOT NULL COMMENT '分区行数（登记时点）',
  first_id BIGINT NULL COMMENT '分区首行主键',
  last_id BIGINT NULL COMMENT '分区末行主键',
  first_prev_hash CHAR(64) NULL COMMENT '首条已封存行前序哈希',
  last_hash CHAR(64) NULL COMMENT '末条已封存行哈希（链尾：验链桥接与新写入续锚）',
  sha256 CHAR(64) NULL COMMENT 'JSONL 摘要（读回校验口径）',
  retention_until DATE NOT NULL COMMENT 'WORM 对象级保留截止（归档日 + 15 年）',
  archived_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_aud_archive_part (table_name, partition_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='审计归档登记（E08-T03 / PLT-AUD-010，作业只追加）';

CREATE TRIGGER aud_archive_ro_upd BEFORE UPDATE ON aud_archive FOR EACH ROW
BEGIN
  IF @crdp_audit_maintenance IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'aud_archive 归档登记只读，禁止修改（PLT-AUD-011）';
  END IF;
END;

CREATE TRIGGER aud_archive_ro_del BEFORE DELETE ON aud_archive FOR EACH ROW
BEGIN
  IF @crdp_audit_maintenance IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'aud_archive 归档登记只读，禁止删除（PLT-AUD-011）';
  END IF;
END;
